"""Step 3 — A1: Pipeline Deployment Agent.

Deploys the SQL scripts and pipeline artifacts generated by the Step 2 DDL Generator Agent
to create the end-to-end data pipelines from ADLS to the Final Gold layer (everything end-to-end
except DataHub, which is handled by A2 Catalog Agent).
"""
from __future__ import annotations

from contextlib import closing
import sqlite3
from pathlib import Path
from typing import Any

import yaml

from src.agents.ddl_generator_agent import run_ddl_generator_agent
from src.models import DatasetMapping, OnboardingManifest


def _sf_type_to_sqlite(sf_type: str) -> str:
    if sf_type == "NUMBER(18,0)":
        return "INTEGER"
    if sf_type.startswith("NUMBER"):
        return "REAL"
    if sf_type == "BOOLEAN":
        return "INTEGER"
    return "TEXT"


def run_a1_provision(dataset: str, registry_root: Path) -> dict[str, Any]:
    """Step 3: Deploy generated 3-layer SQLs and build end-to-end pipeline from ADLS to Final Gold layer."""
    ds_registry = registry_root / dataset
    ddl_path = ds_registry / "ddl.sql"
    mapping_path = ds_registry / "mapping.yaml"

    if not mapping_path.exists():
        raise FileNotFoundError(f"A1 Deployment failed: missing mapping.yaml in {ds_registry}")

    # Ensure Step 2 (DDL Generator Agent) artifacts exist before deployment
    if not ddl_path.exists() or not (ds_registry / "pipeline_deployment_manifest.yaml").exists():
        run_ddl_generator_agent(dataset=dataset, registry_root=registry_root)

    mapping = DatasetMapping.model_validate(yaml.safe_load(mapping_path.read_text(encoding="utf-8")))
    db_path = ds_registry / "local_warehouse.db"
    if db_path.exists():
        db_path.unlink()

    col_defs = ",\n    ".join(
        f"{f.column} {_sf_type_to_sqlite(f.snowflake_type)}" for f in mapping.fields
    )

    with closing(sqlite3.connect(db_path)) as conn:
        cur = conn.cursor()
        # Layer 1 (RAW): Normal Table loaded record-by-record (idempotent on _file_name + _file_sha256 + _record_index)
        cur.execute(
            f"""
            CREATE TABLE IF NOT EXISTS {mapping.targets.raw_table} (
                _file_name TEXT NOT NULL,
                _file_sha256 TEXT NOT NULL,
                _record_index INTEGER NOT NULL DEFAULT 0,
                _source_system TEXT NOT NULL,
                _ingestion_ts TEXT NOT NULL,
                raw_xml TEXT NOT NULL,
                UNIQUE(_file_name, _file_sha256, _record_index)
            );
            """
        )

        # Layer 2 (STAGE): Dynamic Table mirror
        cur.execute(
            f"""
            CREATE TABLE IF NOT EXISTS {mapping.targets.staging_table} (
                {col_defs},
                _file_name TEXT NOT NULL,
                _file_sha256 TEXT NOT NULL,
                _ingestion_ts TEXT NOT NULL
            );
            """
        )

        # Layer 3 (FINAL GOLD): Dynamic Table mirror with version history
        cur.execute(
            f"""
            CREATE TABLE IF NOT EXISTS {mapping.targets.curated_table} (
                {col_defs},
                _row_hash TEXT NOT NULL,
                valid_start_time TEXT NOT NULL,
                valid_end_time TEXT,
                is_current INTEGER NOT NULL DEFAULT 1,
                _source_file TEXT NOT NULL
            );
            """
        )

        # O3: Quarantine
        cur.execute(
            f"""
            CREATE TABLE IF NOT EXISTS {mapping.targets.quarantine_table} (
                dataset TEXT NOT NULL,
                file_name TEXT NOT NULL,
                file_sha256 TEXT NOT NULL,
                gate_id TEXT NOT NULL,
                failure_reason TEXT NOT NULL,
                raw_payload TEXT NOT NULL,
                quarantined_at TEXT NOT NULL,
                replayed INTEGER NOT NULL DEFAULT 0
            );
            """
        )

        # O1: DQ Results
        cur.execute(
            f"""
            CREATE TABLE IF NOT EXISTS {mapping.targets.dq_results_table} (
                dataset TEXT NOT NULL,
                file_name TEXT NOT NULL,
                gate_id TEXT NOT NULL,
                check_name TEXT NOT NULL,
                passed INTEGER NOT NULL,
                details TEXT NOT NULL,
                checked_at TEXT NOT NULL
            );
            """
        )
        conn.commit()

    summary = {
        "dataset": dataset,
        "version": mapping.version,
        "deployed_by": "step3_pipeline_deployment_agent",
        "snowflake_ddl_file": str(ddl_path),
        "deployment_manifest": str(ds_registry / "pipeline_deployment_manifest.yaml"),
        "local_warehouse_db": str(db_path),
        "pipeline_topology": {
            "adls_to_raw": f"Snowpipe (pipe_{dataset}) -> Normal Table ({mapping.targets.raw_table})",
            "raw_to_stage": f"Dynamic Table ({mapping.targets.staging_table}, TARGET_LAG = '5 minutes')",
            "stage_to_gold": f"Dynamic Table ({mapping.targets.curated_table}, TARGET_LAG = '15 minutes')",
        },
        "provisioned_objects": [
            mapping.targets.raw_table,
            mapping.targets.staging_table,
            mapping.targets.curated_table,
            mapping.targets.quarantine_table,
            mapping.targets.dq_results_table,
            f"pipe_{dataset} (PAUSED)",
            f"dynamic_table_{mapping.targets.staging_table}",
            f"dynamic_table_{mapping.targets.curated_table}",
        ],
    }
    (ds_registry / "provisioned_objects.yaml").write_text(
        yaml.safe_dump(summary, sort_keys=False),
        encoding="utf-8",
    )

    manifest_path = ds_registry / "onboarding_manifest.yaml"
    if manifest_path.exists():
        manifest = OnboardingManifest.model_validate(
            yaml.safe_load(manifest_path.read_text(encoding="utf-8"))
        )
        manifest.status = "PROVISIONED"
        manifest_path.write_text(
            yaml.safe_dump(manifest.model_dump(), sort_keys=False),
            encoding="utf-8",
        )

    return summary
