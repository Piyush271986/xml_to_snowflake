-- =============================================================================
-- SNOWFLAKE ACCOUNT BOOTSTRAP SCRIPT FOR XML-TO-SNOWFLAKE PIPELINE
-- Run this script as ACCOUNTADMIN in your Snowflake Web UI (Worksheets)
-- =============================================================================

USE ROLE ACCOUNTADMIN;

-- -----------------------------------------------------------------------------
-- 1. PARAMETERS & ROLES CONFIGURATION
-- -----------------------------------------------------------------------------
-- Roles Hierarchy:
--   ACCOUNTADMIN
--     └── SECURITYADMIN
--     └── SYSADMIN
--           └── DATA_ENGINEER_ROLE  (Owns pipelines, tasks, stages, and tables)
--                 └── DATA_STEWARD_ROLE   (Reads raw/staging/curated, manages quality)
--                 └── DATA_ANALYST_ROLE   (Read-only access to curated dataset & views)
--                 └── DATAHUB_READER_ROLE (Read-only for DataHub catalog ingestion)

CREATE ROLE IF NOT EXISTS DATA_ENGINEER_ROLE COMMENT = 'Role for XML pipeline automation, tasks, and DDL deployments';
CREATE ROLE IF NOT EXISTS DATA_STEWARD_ROLE  COMMENT = 'Role for data governance, schema review, and quality monitoring';
CREATE ROLE IF NOT EXISTS DATA_ANALYST_ROLE  COMMENT = 'Read-only access to published curated datasets and reporting views';
CREATE ROLE IF NOT EXISTS DATAHUB_READER_ROLE COMMENT = 'Service role for DataHub scheduled metadata & lineage ingestion';

-- Build Role Hierarchy under SYSADMIN
GRANT ROLE DATA_ANALYST_ROLE   TO ROLE DATA_STEWARD_ROLE;
GRANT ROLE DATA_STEWARD_ROLE   TO ROLE DATA_ENGINEER_ROLE;
GRANT ROLE DATA_ENGINEER_ROLE  TO ROLE SYSADMIN;
GRANT ROLE DATAHUB_READER_ROLE TO ROLE SYSADMIN;

-- -----------------------------------------------------------------------------
-- 2. DEDICATED WAREHOUSE CREATION (AUTO-SUSPEND = 5 MINUTES)
-- -----------------------------------------------------------------------------
-- 5 minutes = 300 seconds
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
    WITH 
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 300
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Default compute warehouse for XML processing and tasks';

-- Grant warehouse usage to roles
GRANT USAGE, OPERATE ON WAREHOUSE COMPUTE_WH TO ROLE DATA_ENGINEER_ROLE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE DATA_STEWARD_ROLE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE DATA_ANALYST_ROLE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE DATAHUB_READER_ROLE;

-- -----------------------------------------------------------------------------
-- 3. DATABASE & SCHEMAS CREATION
-- -----------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS ENTERPRISE_DW COMMENT = 'Enterprise data warehouse for XML pipeline';

USE DATABASE ENTERPRISE_DW;

-- Schema structure aligned with our operating model
CREATE SCHEMA IF NOT EXISTS RAW     COMMENT = 'D2: Immutable raw XML layer (VARIANT) & Snowpipe landing';
CREATE SCHEMA IF NOT EXISTS STAGING COMMENT = 'D3: Flattened typed staging tables from Streams & Tasks';
CREATE SCHEMA IF NOT EXISTS CURATED COMMENT = 'D4: Published business dataset with SCD Type 2 history';
CREATE SCHEMA IF NOT EXISTS OPS     COMMENT = 'O1 DQ Results, O3 Quarantine, and SLA monitoring views';

-- Grant Database usage
GRANT USAGE ON DATABASE ENTERPRISE_DW TO ROLE DATA_ENGINEER_ROLE;
GRANT USAGE ON DATABASE ENTERPRISE_DW TO ROLE DATA_STEWARD_ROLE;
GRANT USAGE ON DATABASE ENTERPRISE_DW TO ROLE DATA_ANALYST_ROLE;
GRANT USAGE ON DATABASE ENTERPRISE_DW TO ROLE DATAHUB_READER_ROLE;

-- -----------------------------------------------------------------------------
-- 4. SCHEMA-LEVEL RBAC PERMISSIONS
-- -----------------------------------------------------------------------------

-- --- DATA_ENGINEER_ROLE (Full Owner / Operator) ---
GRANT ALL PRIVILEGES ON SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATA_ENGINEER_ROLE;

-- Allow Data Engineer to execute Serverless / Warehouse Tasks
GRANT EXECUTE TASK ON ACCOUNT TO ROLE DATA_ENGINEER_ROLE;

-- Future grants so tables created by agents automatically inherit permissions
GRANT ALL PRIVILEGES ON FUTURE TABLES    IN SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TABLES    IN SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TABLES    IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TABLES    IN SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE STREAMS   IN SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TASKS     IN SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATA_ENGINEER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TASKS     IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_ENGINEER_ROLE;

-- --- DATA_STEWARD_ROLE (Governance, Review, Read across all stages) ---
GRANT USAGE ON SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATA_STEWARD_ROLE;
GRANT USAGE ON SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATA_STEWARD_ROLE;
GRANT USAGE ON SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_STEWARD_ROLE;
GRANT USAGE ON SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATA_STEWARD_ROLE;

GRANT SELECT ON ALL TABLES    IN SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATA_STEWARD_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATA_STEWARD_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_STEWARD_ROLE;
GRANT SELECT, UPDATE ON ALL TABLES IN SCHEMA ENTERPRISE_DW.OPS TO ROLE DATA_STEWARD_ROLE; -- Can replay quarantine

GRANT SELECT ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATA_STEWARD_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATA_STEWARD_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_STEWARD_ROLE;
GRANT SELECT, UPDATE ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.OPS TO ROLE DATA_STEWARD_ROLE;

-- --- DATA_ANALYST_ROLE (Consumer of Curated & Ops Views) ---
GRANT USAGE ON SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_ANALYST_ROLE;
GRANT USAGE ON SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATA_ANALYST_ROLE;

GRANT SELECT ON ALL TABLES    IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_ANALYST_ROLE;
GRANT SELECT ON ALL VIEWS     IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_ANALYST_ROLE;
GRANT SELECT ON ALL VIEWS     IN SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATA_ANALYST_ROLE;

GRANT SELECT ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_ANALYST_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATA_ANALYST_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATA_ANALYST_ROLE;

-- --- DATAHUB_READER_ROLE (Read-only metadata crawler & lineage) ---
GRANT USAGE ON SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATAHUB_READER_ROLE;
GRANT USAGE ON SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATAHUB_READER_ROLE;
GRANT USAGE ON SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATAHUB_READER_ROLE;
GRANT USAGE ON SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATAHUB_READER_ROLE;

GRANT SELECT ON ALL TABLES    IN SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATAHUB_READER_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATAHUB_READER_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATAHUB_READER_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATAHUB_READER_ROLE;

GRANT SELECT ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.RAW     TO ROLE DATAHUB_READER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.STAGING TO ROLE DATAHUB_READER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.CURATED TO ROLE DATAHUB_READER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ENTERPRISE_DW.OPS     TO ROLE DATAHUB_READER_ROLE;

-- Enable DataHub to read query history for automated lineage & usage analytics
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE DATAHUB_READER_ROLE;

